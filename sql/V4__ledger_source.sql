-- 个人生活管理软件 · 增量脚本 V4：记账来源追踪（凭证入账 / 工资自动入账）
-- 说明：
--   1. ledger_record 增加来源字段，用于标识流水是怎么来的，
--      并作为「幂等」依据（同一凭证、同一月份工资不得重复入账）。
--   2. source_type: 1=手动记账 2=凭证入账 3=工资自动入账
--   3. source_id  : 凭证入账存 receipt_image.id；
--                   工资入账存 YYYYMM（如 202610），用于按月防重。
--   4. 收支方向仍由 ledger_category.type 派生（H6），本脚本不新增 type 字段。
-- =====================================================================

USE `life_manager`;

SET NAMES utf8mb4;

-- =====================================================================
-- 九、记账来源追踪
-- =====================================================================

ALTER TABLE `ledger_record`
  ADD COLUMN `source_type` TINYINT NOT NULL DEFAULT 1
      COMMENT '来源: 1=手动记账 2=凭证入账 3=工资自动入账' AFTER `remark`,
  ADD COLUMN `source_id`   BIGINT  DEFAULT NULL
      COMMENT '来源单据ID(凭证ID / 工资YYYYMM)' AFTER `source_type`,
  ADD KEY `idx_user_source` (`user_id`, `source_type`, `source_id`);

